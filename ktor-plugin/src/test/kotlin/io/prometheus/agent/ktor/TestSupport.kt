package io.prometheus.agent.ktor

import java.net.ServerSocket

// A port nothing listens on, taken from the OS, then closed: a proxy an agent starts with, and keeps trying to reach
internal fun closedPort(): Int = ServerSocket(0).use { it.localPort }
